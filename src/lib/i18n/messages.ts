export function translateArabic(source: string) {
  const normalized = source.trim();
  const translated = englishMessages[normalized];
  if (translated) return source.replace(normalized, translated);

  const userCount = normalized.match(/^(\d+) مستخدم$/);
  if (userCount) return `${userCount[1]} users`;
  const pageCount = normalized.match(/^صفحة (\d+) من (\d+)$/);
  if (pageCount) return `Page ${pageCount[1]} of ${pageCount[2]}`;
  return source;
}
